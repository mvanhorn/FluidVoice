    private func preferred(
        _ bundleIdentifier: String,
        frontmost: String? = nil
    ) -> TypingService.VisualStudioCodeRoutingTarget {
        self.identity(
            preferred: bundleIdentifier,
            hasPreferredTarget: true,
            frontmost: frontmost
        )
    }

    private func identity(
        preferred: String? = nil,
        hasPreferredTarget: Bool = false,
        focused: String? = nil,
        hasFocusedApplication: Bool = false,
        frontmost: String? = nil
    ) -> TypingService.VisualStudioCodeRoutingTarget {
        TypingService.VisualStudioCodeRoutingTarget(
            hasPreferredTarget: hasPreferredTarget,
            preferredBundleIdentifier: preferred,
            hasFocusedApplication: hasFocusedApplication,
            focusedBundleIdentifier: focused,
            frontmostBundleIdentifier: frontmost
        )
    }

    private func routes(
        utf16Count: Int,
        target: TypingService.VisualStudioCodeRoutingTarget
    ) -> Bool {
        TypingService.routesMultiChunkVisualStudioCodeInputThroughClipboard(
            utf16Count: utf16Count,
            target: target
        )
    }
