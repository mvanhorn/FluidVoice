        let restoredBitmap = try XCTUnwrap(NSBitmapImageRep(data: restoredPNG))
        let restoredColor = try XCTUnwrap(restoredBitmap.colorAt(x: 0, y: 0)?.usingColorSpace(.deviceRGB))
        XCTAssertGreaterThan(restoredColor.redComponent, 0.8)
        XCTAssertGreaterThan(restoredColor.redComponent, restoredColor.greenComponent + 0.5)
        XCTAssertGreaterThan(restoredColor.redComponent, restoredColor.blueComponent + 0.5)
    }

