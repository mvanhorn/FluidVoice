@MainActor
final class PasteboardOwnershipRegressionTests: XCTestCase {
    func testFailureRestorationPreservesNewerCopy() throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        pasteboard.setString("original", forType: .string)
        let manager = SystemPasteboardManager(pasteboard: pasteboard)
        let snapshot = try XCTUnwrap(manager.captureSnapshot())
        XCTAssertTrue(manager.writeTemporaryText("dictation", sessionID: "session"))
        pasteboard.clearContents()
        pasteboard.setString("new user copy", forType: .string)
        XCTAssertFalse(manager.restoreTemporarySnapshot(snapshot, sessionID: "session", expectedText: "dictation"))
        XCTAssertEqual(pasteboard.string(forType: .string), "new user copy")
    }

    func testMatchingMarkersDoNotOverrideNewerClipboardGeneration() throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        pasteboard.setString("original", forType: .string)
        let manager = SystemPasteboardManager(pasteboard: pasteboard)
        let snapshot = try XCTUnwrap(manager.captureSnapshot())
        XCTAssertTrue(manager.writeTemporaryText("dictation", sessionID: "session"))
        let temporary = try XCTUnwrap(pasteboard.pasteboardItems?.first)
        let copy = NSPasteboardItem()
        for type in temporary.types {
            try copy.setData(XCTUnwrap(temporary.data(forType: type)), forType: type)
        }
        pasteboard.clearContents()
        XCTAssertTrue(pasteboard.writeObjects([copy]))
        XCTAssertFalse(manager.isOwned(sessionID: "session", expectedText: "dictation"))
        XCTAssertFalse(manager.restoreTemporarySnapshot(snapshot, sessionID: "session", expectedText: "dictation"))
        XCTAssertEqual(pasteboard.string(forType: .string), "dictation")
    }

    func testUnchangedTemporaryClipboardCanBeRestored() throws {
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        pasteboard.setString("original", forType: .string)
        let manager = SystemPasteboardManager(pasteboard: pasteboard)
        let snapshot = try XCTUnwrap(manager.captureSnapshot())
        XCTAssertTrue(manager.writeTemporaryText("dictation", sessionID: "session"))
        XCTAssertTrue(manager.restoreTemporarySnapshot(snapshot, sessionID: "session", expectedText: "dictation"))
        XCTAssertEqual(pasteboard.string(forType: .string), "original")
    }
}

@MainActor
final class VisualStudioCodeInsertionRoutingTests: XCTestCase {
    private let visualStudioCode = "com.microsoft.VSCode"
    private let insiders = "com.microsoft.VSCodeInsiders"
    private let exploration = "com.microsoft.VSCodeExploration"
    private let textEdit = "com.apple.TextEdit"
    private let electron = "com.github.Electron"
    private let cursor = "com.todesktop.230313mzl4w4u92"
    private let ghostty = "com.mitchellh.ghostty"

    func testProductionRoutingAt199_200And201UTF16Units() {
        let limit = TypingService.cgEventUnicodeChunkSize
        XCTAssertEqual(limit, 200)
        let vscode = self.preferred(self.visualStudioCode)

        XCTAssertFalse(self.routes(utf16Count: 199, target: vscode))
        XCTAssertFalse(self.routes(utf16Count: limit - 1, target: vscode))
        XCTAssertFalse(self.routes(utf16Count: 200, target: vscode))
        XCTAssertFalse(self.routes(utf16Count: limit, target: vscode))
        XCTAssertTrue(self.routes(utf16Count: 201, target: vscode))
        XCTAssertTrue(self.routes(utf16Count: limit + 1, target: vscode))
        XCTAssertTrue(self.routes(utf16Count: 201, target: self.preferred(self.insiders)))
        XCTAssertTrue(self.routes(utf16Count: 201, target: self.preferred(self.exploration)))
    }

    func testEmojiCrossingTheChunkBoundaryUsesClipboardDelivery() {
        let limit = TypingService.cgEventUnicodeChunkSize
        let crossing = String(repeating: "a", count: limit - 1) + "😀"
        XCTAssertEqual(crossing.count, limit)
        XCTAssertEqual(crossing.utf16.count, 201)
        XCTAssertEqual(crossing.utf16.count, limit + 1)
        XCTAssertTrue(self.routes(utf16Count: crossing.utf16.count, target: self.preferred(self.visualStudioCode)))

        let fitting = String(repeating: "😀", count: limit / 2)
        XCTAssertEqual(fitting.utf16.count, 200)
        XCTAssertFalse(self.routes(utf16Count: fitting.utf16.count, target: self.preferred(self.visualStudioCode)))

        let overflowing = String(repeating: "😀", count: (limit / 2) + 1)
        XCTAssertEqual(overflowing.utf16.count, 202)
        XCTAssertLessThan(overflowing.count, limit)
        XCTAssertTrue(self.routes(utf16Count: overflowing.utf16.count, target: self.preferred(self.visualStudioCode)))
    }

    func testEmptyInputDoesNotUseVisualStudioCodeClipboardRouting() {
        XCTAssertFalse(self.routes(utf16Count: 0, target: self.preferred(self.visualStudioCode)))
        XCTAssertFalse(self.routes(utf16Count: 0, target: self.preferred(self.textEdit)))
    }

    func testLongMultilineVisualStudioCodeInputChoosesClipboardDelivery() {
        let transcript = longNumberedUnicodeTranscript()
        XCTAssertGreaterThan(transcript.utf16.count, TypingService.cgEventUnicodeChunkSize)
        XCTAssertTrue(transcript.hasPrefix("BEGIN 😀"))
        XCTAssertTrue(transcript.contains("\n0450 café — 语音 — middle — 0450"))
        XCTAssertTrue(transcript.hasSuffix("END ✨"))
        XCTAssertTrue(transcript.contains("\n"))

        XCTAssertTrue(self.routes(utf16Count: transcript.utf16.count, target: self.preferred(self.visualStudioCode)))
        XCTAssertTrue(
            TypingService.usesClipboardDelivery(
                mode: .standard,
                isGhosttyTarget: false,
                routesLongVSCodeThroughClipboard: true
            )
        )
        XCTAssertFalse(
            self.routes(
                utf16Count: transcript.utf16.count,
                target: self.preferred(self.textEdit, frontmost: self.visualStudioCode)
            )
        )
    }

    func testPreferredTargetPrecedesADifferentFrontmostApp() {
        let longCount = TypingService.cgEventUnicodeChunkSize + 50
